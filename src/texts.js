export function generateFullReading(context) {
  const lightParts = [];

  // 1. 宫位解读
  const gongText = generateGongText(context);
  if (gongText) lightParts.push(gongText);

  // 2. 体用解读
  const etText = generateElementTiYongText(context);
  if (etText) lightParts.push(etText);

  // 3. 旺衰解读
  const wangText = generateWangText(context);
  if (wangText) lightParts.push(wangText);

  // 4. 天机线解读（如果有）
  if (context.linePosition && context.linePosition !== 'offline') {
    const lineText = generateLineText(context);
    if (lineText) lightParts.push(lineText);
  }

  // 5. 差值解读（如果有）
  if (context.diff !== undefined && context.diff !== null) {
    const diffText = generateDiffText(context);
    if (diffText) lightParts.push(diffText);
  }

  // 6. 注入巴纳姆反转
  const barnum = injectBarnum();
  if (barnum) {
    lightParts.splice(Math.floor(Math.random() * (lightParts.length + 1)), 0, barnum);
  }

  // 7. 注入情绪与对话感
  const injection = injectEmotionAndDialogue();
  if (injection) {
    lightParts.splice(Math.floor(Math.random() * (lightParts.length + 1)), 0, injection);
  }

  // 8. 结尾
  lightParts.push(pick(closingLines));

  // 阴影接口（现在根据情况设置非空内容）
  let shadow = '';
  if (context.diff > 5 && context.wangState === '死') {
    shadow = '但别忘了，牌只是照见你心里的种子。未来的走向，在你接下来的每一个选择里。';
  } else if (context.diff > 5 && context.linePosition === '结果') {
    shadow = '你看到的结果，可能只是暂时的形态。真正的答案需要时间去验证。';
  } else {
    shadow = '这一面的镜子里，你看到了什么？有时候，比牌更重要的，是你读牌时自己的反应。';
  }

  return {
    light: lightParts.join(' '),
    shadow: shadow,
  };
}

