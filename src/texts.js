export function generateGongText(context) {
  const gongId = context.gong?.id;
  const intent = context.intent || 'default';
  if (!gongId || !gongPhrases[gongId]) return pick([
    '这个宫位的气息正在流入你的感知中，你可以先感受它，再解读它',
    '你此刻的注意力正被某个方向吸引，也许你还不太确定那是什么'
  ]);

  const baseSet = gongPhrases[gongId];
  const selectedLead = pick(getPhraseSet(baseSet, 'lead', intent) || baseSet.default?.lead || []);
  const selectedTrait = pick(getPhraseSet(baseSet, 'trait', intent) || baseSet.default?.trait || []);
  const selectedHidden = pick(getPhraseSet(baseSet, 'hidden', intent) || baseSet.default?.hidden || []);

  if (!selectedLead || !selectedTrait) return '';

  // 组装宫位描述
  let result = selectedLead;

  // 根据差值决定是否插入强度感知
  const diff = context.diff;
  if (diff !== undefined && diff !== null) {
    const level = getIntensityLevel(diff);
    const adv = pick(intensityMap[level]?.adv || ['']);
    const verb = pick(intensityMap[level]?.verb || ['']);
    const effect = pick(intensityMap[level]?.effect || ['']);
    if (adv && verb) {
      result += '，' + adv + ' ' + verb + '你的注意力';
      if (effect && Math.random() > 0.4) result += '，' + effect;
    }
  }

  // 插入特质
  if (Math.random() > 0.3) {
    result += '，' + selectedTrait;
  }

  // 插入隐藏层（约40%概率）
  if (Math.random() > 0.6 && selectedHidden) {
    result += '，' + selectedHidden;
  }

  // 随机插入反问或巴纳姆反转（约30%概率）
  if (Math.random() > 0.7) {
    const prompt = pick(reflectionPrompts);
    result += '。' + prompt;
  }

  // 插入对话感短语（约20%概率）
  if (Math.random() > 0.8) {
    const dialogue = pick(dialoguePhrases);
    result += '。' + dialogue;
  }

  return result;
}

export function generateElementTiYongText(context) {
  const tiWx = context.ti?.element;
  const yongWx = context.yong?.element;
  const relation = context.tiYongRelation || '同我';
  const intent = context.intent || 'default';

  if (!tiWx || !yongWx) return pick([
    '体用之间的关系正在形成一种微妙的张力，你可以先感受它们各自的状态'
  ]);

  const tiPhrase = pick(elementPhrases[tiWx]?.positive || ['']).replace(/^[,，、]/, '');
  const yongPhrase = pick(elementPhrases[yongWx]?.positive || ['']).replace(/^[,，、]/, '');
  const relationPhrase = pick(getPhraseSet(tiYongPhrases, relation, intent) || ['']);

  if (!tiPhrase || !yongPhrase || !relationPhrase) return '';

  const directionMap = {
    '生我': '滋养',
    '我生': '流向',
    '克我': '压力',
    '我克': '转化',
    '同我': '平衡'
  };
  const direction = directionMap[relation] || '共振';

  let result = `体牌属${tiWx}，你像${tiPhrase}。用牌属${yongWx}，你所关注的事像${yongPhrase}。`;

  // 插入关系描述
  result += relationPhrase;

  // 插入方向感
  if (Math.random() > 0.4) {
    result += `这种${direction}的关系，是现在的能量通道。`;
  }

  // 随机插入情绪词或反问
  if (Math.random() > 0.7) {
    const emotion = pick(emotionWords);
    result += emotion + '，' + pick([
      '这种能量的交汇让你感到既熟悉又陌生',
      '你正在两种力量之间寻找一个平衡点',
      '你可能还没有完全意识到这种互动对你的影响'
    ]);
  }

  if (Math.random() > 0.8) {
    const dialogue = pick(dialoguePhrases);
    result += '。' + dialogue;
  }

  return result;
}

