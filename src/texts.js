// ---------- 11.2 工具函数 ----------
function pick(arr) {
  if (!arr || arr.length === 0) return '';
  return arr[Math.floor(Math.random() * arr.length)];
}

function getIntensityLevel(diff) {
  if (diff <= 1) return 'tiny';
  if (diff <= 3) return 'small';
  if (diff <= 5) return 'medium';
  if (diff <= 8) return 'large';
  return 'huge';
}

// ---------- 11.3 生成函数 ----------
function generateGongText(ctx) {
  const g = ctx.gong;
  const phrases = gongPhrases[g.id];
  if (!phrases) return '';
  const parts = [
    pick(phrases.lead),
    pick(phrases.trait),
    pick(phrases.hidden),
    `这就像${pick(phrases.metaphor)}。`
  ];
  // 随机组合顺序，增加变化
  let order = [0,1,2,3];
  // 打乱顺序
  for (let i = order.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order.map(i => parts[i]).join(' ');
}

function generateElementTiYongText(ctx) {
  const ele = ctx.card?.element || '土';
  const relation = ctx.tiYongRelation || '同我';
  const t = tiYongPhrases[relation];
  if (!t) return '';
  const e = elementPhrases[ele] || elementPhrases['土'];
  const parts = [
    `你的${ele}特质，在这种“${relation}”的关系下，${pick(e.negative)}。`,
    `${pick(t.consequence)}。`,
    `${pick(t.advice)}。`
  ];
  // 随机打乱
  const shuffled = parts.sort(() => Math.random() - 0.5);
  return shuffled.join(' ');
}

function generateWangText(ctx) {
  const w = ctx.wangState || '休';
  const phrase = wangPhrases[w];
  if (!phrase) return '';
  return `当前能量${phrase.desc}。${phrase.hint}。`;
}

function generateLineText(ctx) {
  const pos = ctx.linePosition || 'middle';
  const phrases = linePhrases[pos];
  if (!phrases) return '';
  return `天机线位于“${pos}”阶段：${pick(phrases)}`;
}

function generateDiffText(ctx) {
  const diff = ctx.diff ?? 0;
  const level = getIntensityLevel(diff);
  const map = intensityMap[level];
  if (!map) return '';
  return `差值${map.adv}，说明你在这个位置的用力程度${map.verb}你的舒适区。`;
}

function generateSpecialText(ctx) {
  const parts = [];
  if (ctx.hasVoid) parts.push('这个宫位处于空亡状态，它不是没有信息，而是信息还在打包中。你需要等待它解压缩。');
  if (ctx.hasOpposition) parts.push('逢冲，能量正在剧烈震荡。这可能是突破的前奏，也可能是混乱的开始。');
  if (ctx.hasHe) parts.push('逢合，能量被暂时绑定。你被这件事或这段关系缠住了，需要看清是滋养还是消耗。');
  if (ctx.hasMa) parts.push('马星动，你的心是悬着的，你的脚是准备迈出去的。不要抗拒这种奔波。');
  return parts.join(' ');
}

function injectEmotionAndDialogue() {
  let result = '';
  if (Math.random() < 0.4) {
    result += pick(emotionWords) + '，';
  }
  if (Math.random() < 0.3) {
    result += pick(dialoguePhrases) + ' ';
  }
  return result;
}

// ---------- 11.4 主入口：生成完整解读 ----------
export function generateFullReading(context) {
  // context 结构：
  // { gong: { id, name, element }, card: { value, element, suit }, tiYongRelation, wangState, linePosition, diff, hasVoid, hasOpposition, hasHe, hasMa }
  const parts = [];

  // 1. 宫位描述
  const gongText = generateGongText(context);
  if (gongText) parts.push(gongText);

  // 2. 五行+体用
  const etText = generateElementTiYongText(context);
  if (etText) parts.push(etText);

  // 3. 旺衰
  const wangText = generateWangText(context);
  if (wangText) parts.push(wangText);

  // 4. 天机线
  if (context.linePosition) {
    const lineText = generateLineText(context);
    if (lineText) parts.push(lineText);
  }

  // 5. 差值
  if (context.diff !== undefined && context.diff !== null) {
    const diffText = generateDiffText(context);
    if (diffText) parts.push(diffText);
  }

  // 6. 特殊状态
  if (context.hasVoid || context.hasOpposition || context.hasHe || context.hasMa) {
    const spText = generateSpecialText(context);
    if (spText) parts.push(spText);
  }

  // 7. 随机插入情绪词和对话感（约40%概率）
  const injection = injectEmotionAndDialogue();
  if (injection) {
    // 在中间位置随机插入
    const insertIndex = Math.floor(Math.random() * (parts.length + 1));
    parts.splice(insertIndex, 0, injection);
  }

  // 8. 结尾收束（随机选择）
  const closings = [
    '这只是一个切面。你的现实比牌面丰富得多。',
    '记住：你是照镜子的人，不是镜子里的人。',
    '牌给了你一个视角，但行动还得靠你自己。',
    '你在牌中看到的，只是你当下注意力聚焦的那一点。',
    '无论牌面如何，你此刻的呼吸，才是你真正的锚点。'
  ];
  parts.push(pick(closings));

  // 用空行连接，形成段落感
  return parts.join('\n\n');
}

