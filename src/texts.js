export function generateGongText(context) {
  const gongId = context.gong?.id;
  const intent = context.intent || 'default';
  if (!gongId || !gongPhrases[gongId]) return pick([
    '这个宫位的气息正在流入你的感知中，你可以先感受它，再解读它。',
    '你此刻的注意力正被某个方向吸引，也许你还不太确定那是什么。'
  ]);

  const baseSet = gongPhrases[gongId];
  const selectedLead = pick(getPhraseSet(baseSet, 'lead', intent) || baseSet.default?.lead || []);
  const selectedTrait = pick(getPhraseSet(baseSet, 'trait', intent) || baseSet.default?.trait || []);
  const selectedHidden = pick(getPhraseSet(baseSet, 'hidden', intent) || baseSet.default?.hidden || []);

  if (!selectedLead || !selectedTrait) return '';

  let result = selectedLead;

  // 根据差值决定是否插入强度感知
  const diff = context.diff;
  if (diff !== undefined && diff !== null) {
    const level = getIntensityLevel(diff);
    const adv = pick(intensityMap[level]?.adv || ['']);
    const verb = pick(intensityMap[level]?.verb || ['']);
    const effect = pick(intensityMap[level]?.effect || ['']);
    if (adv && verb) {
      result += '，' + adv + verb + '你的注意力';
      if (effect && Math.random() > 0.4) result += '，' + effect;
    }
  }

  if (Math.random() > 0.3) {
    result += '，' + selectedTrait;
  }

  if (Math.random() > 0.6 && selectedHidden) {
    result += '，' + selectedHidden;
  }

  if (Math.random() > 0.7) {
    const prompt = pick(reflectionPrompts);
    result += '。' + prompt;
  }

  if (Math.random() > 0.8) {
    const dialogue = pick(dialoguePhrases);
    result += '。' + dialogue;
  }

  return result;
}

