export function generateDiffText(context) {
  const diff = context.diff;
  if (diff === undefined || diff === null) return '';

  const level = getIntensityLevel(diff);
  const adv = pick(intensityMap[level]?.adv || ['']);
  const verb = pick(intensityMap[level]?.verb || ['']);
  const effect = pick(intensityMap[level]?.effect || ['']);

  if (!adv || !verb || !effect) return '';

  let result = `差值体现为一种${diff <= 3 ? '近乎同步' : diff <= 6 ? '可感知的错位' : '显著的距离'}，${effect}`;

  // 随机插入情绪词
  if (Math.random() > 0.5) {
    const emotion = pick(emotionWords);
    result += '。' + emotion + '，' + pick([
      '你正在被这种张力推着走',
      '你也许还没有完全意识到这件事的分量',
      '这种错位感本身，就是一种信息'
    ]);
  }

  return result;
}

