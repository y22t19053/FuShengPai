/** 时支 → 象义条目（未命中返回 null） */
export function getHourEntry(zhi) {
  if (!zhi) return null;
  return HOUR_POOL.find(h => h.zhi === zhi) || null;
}

/**
 * 按「日期 + 时辰」确定性取一句（同日同时辰固定，次日自动换新）。
 * @param {string} seedText 种子（如 '2026-08-06'）
 * @param {string} zhi 时支（子~亥）
 * @returns {string} 象义句子
 */
export function pickHourLine(seedText, zhi) {
  const entry = getHourEntry(zhi);
  if (!entry) return '';
  const seed = String(seedText || '') + '|' + zhi;
  let h = 0x811c9dc5;
  for (const ch of seed) {
    h ^= ch.charCodeAt(0);
    h = (h * 0x01000193) >>> 0;
  }
  return entry.lines[h % entry.lines.length];
}
