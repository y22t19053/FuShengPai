/** 花色气质速查（用于把画面接回牌面，不代替画面） */
export const SUIT_IMAGE_THEME = {
  '♠': { domain: '暗处与压力', hint: '这张牌的画面多发生在你看不见的地方，先解决「流出去的东西」。' },
  '♥': { domain: '关系与情绪', hint: '这张牌的画面里总有别人，先把「谁在给谁添柴」说清楚。' },
  '♣': { domain: '日常与生长', hint: '这张牌的画面很慢，别指望今天见效，今天只要不挪它。' },
  '♦': { domain: '秤、钱与界线', hint: '这张牌的画面在称重，先把「拿什么换什么」摆到台面上。' },
  '天': { domain: '局外', hint: '这张牌不在局里，它说的是你站在什么位置看这件事。' },
  '人': { domain: '人群', hint: '这张牌在人群里，它说的是你在别人中间的样子。' },
};

function cardKey(card) {
  if (!card) return '';
  if (card.isJoker) return card.type === '大王' ? '大王' : '小王';
  return `${card.suit || ''}${card.rank || ''}`;
}

/**
 * 取一张牌的意象（画面 + 一个动作）。
 * @param {object} card { suit, rank, isJoker, type }
 * @returns {{ image: string, action: string, domain: string, hint: string } | null}
 */
export function getCardImage(card) {
  const key = cardKey(card);
  const item = IMAGES[key];
  if (!item) return null;
  const suitKey = card.isJoker ? (card.type === '大王' ? '天' : '人') : card.suit;
  const theme = SUIT_IMAGE_THEME[suitKey] || SUIT_IMAGE_THEME['♣'];
  return { image: item.image, action: item.action, domain: theme.domain, hint: theme.hint };
}

/** 全部意象（供审查 / 测试遍历，勿在 UI 里遍历） */
export const CARD_IMAGE_POOL = Object.entries(IMAGES).map(([key, v]) => ({ key, ...v }));

/** 只取画面，不取建议（用于分享图等不能给动作的地方） */
export function getCardImageLine(card) {
  const it = getCardImage(card);
  return it ? it.image : '';
}
