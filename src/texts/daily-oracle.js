/** 日期 → 确定性种子（同一天固定；无日期时按自然日） */
function dateSeed(dateStr) {
  const m = dateStr ? String(dateStr).match(/(\d{4})[-/](\d{1,2})[-/](\d{1,2})/) : null;
  if (m) return Number(m[1]) * 372 + Number(m[2]) * 31 + Number(m[3]);
  return Math.floor(Date.now() / 86400000);
}

/** 确定性伪随机（xorshift32：固定种子 → 同一天结果不变；相邻日期完全发散） */
function makeRnd(seed) {
  let s = seed >>> 0;
  if (s === 0) s = 0x9e3779b9;
  return () => {
    s ^= s << 13;
    s ^= s >>> 17;
    s ^= s << 5;
    s = s >>> 0;
    return (s % 233280) / 233280;
  };
}

/**
 * 构建当日日运 oracle（四板块各取 1 条，同一天内固定，不同类别按五行筛选）
 * @param {Object} [opts] - { wx: 五行, dateStr: '2026-08-03' }
 * @returns {{wx, mood, jianchu, chong, combo, yi, ji}}
 */
export function buildDailyOracle({ wx = '土', dateStr } = {}) {
  const seed = dateSeed(dateStr);
  const rnd = makeRnd(seed);
  const pick = (arr) => arr[Math.floor(rnd() * arr.length)];

  const moodPool = MOOD_BY_WX[wx] || MOOD_BY_WX['土'];
  const mood = pick(moodPool);
  const jianchu = JIANGCHU[seed % 12];
  const chong = CHONG[(seed + 5) % 12]; // 与建除错开，避免同一位

  // 组合短句：优先 五行×建除 精确匹配，其次同五行，最后全池
  let comboPool = COMBO.filter((c) => c.wx === wx && c.jianchu === jianchu.name);
  if (!comboPool.length) comboPool = COMBO.filter((c) => c.wx === wx);
  if (!comboPool.length) comboPool = COMBO;
  const combo = pick(comboPool);

  return {
    wx,
    mood,
    jianchu,
    chong,
    combo,
    yi: (jianchu.yi || []).slice(0, 3),
    ji: (jianchu.ji || []).slice(0, 3),
    seed,
  };
}
